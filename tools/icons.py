#!/usr/bin/env python3
"""Generate self-contained Lucide SVG paths for Carrel. Run: python3 tools/icons.py

The checked-in output lets the Android WebView work with no network.
Uses installed lucide-static files first, then downloads trusted Lucide SVGs.
Lucide is licensed under ISC: https://lucide.dev/license
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = json.loads("{\"today\":\"timer\",\"plan\":\"calendar-days\",\"stats\":\"chart-column\",\"settings\":\"settings\",\"back\":\"arrow-left\",\"close\":\"x\",\"prev\":\"chevron-left\",\"next\":\"chevron-right\",\"open\":\"chevron-right\",\"expand\":\"chevron-down\",\"add\":\"plus\",\"minus\":\"minus\",\"more\":\"ellipsis-vertical\",\"edit\":\"pencil\",\"delete\":\"trash-2\",\"start\":\"play\",\"stop\":\"square\",\"break\":\"coffee\",\"focus\":\"maximize-2\",\"unfocus\":\"minimize-2\",\"pomodoro\":\"hourglass\",\"urge\":\"zap\",\"drift\":\"wind\",\"park\":\"bookmark\",\"tasks\":\"list-todo\",\"week\":\"calendar-range\",\"day\":\"calendar-1\",\"jump\":\"locate-fixed\",\"deadline\":\"flag\",\"backlog\":\"inbox\",\"weekly\":\"calendar-clock\",\"busy\":\"briefcase\",\"schedule\":\"calendar-plus\",\"autoplan\":\"wand-sparkles\",\"fit\":\"shrink\",\"tomorrow\":\"arrow-right\",\"later\":\"clock\",\"carry\":\"history\",\"pin\":\"pin\",\"unpin\":\"pin-off\",\"split\":\"split\",\"dup\":\"copy-plus\",\"copy\":\"copy\",\"wrap\":\"moon\",\"note\":\"sparkles\",\"done\":\"check\",\"undo\":\"undo-2\",\"rate1\":\"battery-low\",\"rate2\":\"battery-medium\",\"rate3\":\"battery-full\",\"offline\":\"cloud-off\",\"warn\":\"triangle-alert\",\"refresh\":\"refresh-cw\",\"activities\":\"shapes\",\"timer\":\"timer-reset\",\"daycfg\":\"sunrise\",\"bell\":\"bell\",\"gcal\":\"calendar-sync\",\"export\":\"download\",\"user\":\"circle-user\",\"info\":\"info\",\"keys\":\"keyboard\",\"signin\":\"log-in\",\"signout\":\"log-out\",\"archive\":\"archive\",\"unarchive\":\"archive-restore\",\"up\":\"arrow-up\",\"down\":\"arrow-down\",\"insights\":\"lightbulb\",\"patterns\":\"grid-3x3\",\"exam\":\"graduation-cap\",\"due\":\"file-text\",\"other\":\"flag\",\"high\":\"chevrons-up\",\"normal\":\"equal\",\"low\":\"chevrons-down\",\"repeat\":\"repeat\"}")
ALIASES = json.loads("{\"play\":\"start\",\"cup\":\"break\",\"moon\":\"wrap\",\"plus\":\"add\",\"left\":\"prev\",\"right\":\"open\",\"sliders\":\"settings\",\"clock\":\"later\",\"bars\":\"stats\",\"grid\":\"patterns\",\"check\":\"done\",\"x\":\"close\",\"skip\":\"next\",\"trash\":\"delete\",\"download\":\"export\",\"dots\":\"more\",\"shrink\":\"fit\",\"wand\":\"autoplan\",\"cal\":\"plan\",\"flag\":\"deadline\",\"inbox\":\"backlog\"}")
SRC = ROOT / "node_modules" / "lucide-static" / "icons"
OUT = ROOT / "web" / "ui" / "icons.js"
URL = "https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/{name}.svg"


def inner_svg(name):
    f = SRC / (name + ".svg")
    if f.exists():
        source = f.read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL.format(name=name), timeout=20) as response:
            source = response.read().decode("utf-8")
    found = re.search(r"<svg\\b[^>]*>([\\s\\S]*?)</svg>", source, re.I)
    if not found:
        raise ValueError(f"invalid SVG: {name}")
    markup = found.group(1).strip()
    if re.search(r"<script|<foreignObject|\\bon\\w+\\s*=", markup, re.I):
        raise ValueError(f"unsafe SVG markup: {name}")
    return re.sub(r"\\s{2,}", " ", markup)


def main():
    try:
        shapes = {slug: inner_svg(slug) for slug in sorted(set(ICONS.values()))}
    except (OSError, ValueError) as exc:
        sys.exit(f"Icon generation failed; leaving existing output unchanged: {exc}")
    data = {name: shapes[slug] for name, slug in ICONS.items()}
    for old, new in ALIASES.items():
        data[old] = data[new]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Lucide icons (ISC), generated by tools/icons.py.\\n"
                   "// R0a loads this after core/state.js declares P.\\n"
                   "Object.assign(P, " + json.dumps(data, ensure_ascii=False, indent=2) + ");\\n",
                   encoding="utf-8")
    print(f"Bundled {len(data)} icon names into {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
